"""
Сумма натуральных чисел
Напишите рекурсивную функцию summa, которая будет суммировать все числа от 1 до N включительно.
Число N поступает внутрь функции в качестве аргумента
"""


def summa(n: int) -> int:
    # Базовый случай: если n равно 1, возвращаем 1
    if n == 1:
        return 1
    # Рекурсивный случай: n + сумма чисел от 1 до (n-1)
    return n + summa(n - 1)
