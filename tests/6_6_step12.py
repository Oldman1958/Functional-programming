"""
А вы знали, что цифры на банковской карте выбираются не просто случайным образом?

Сумма определенных цифр на карте должна проходить условия алгоритма Луна

Упрощенная версия алгоритма выглядит так:

- Цифры проверяемой последовательности нумеруются справа налево;

- Цифры, оказавшиеся на нечётных местах, остаются без изменений;

- Цифры, стоящие на чётных местах, умножаются на 2.
  Если в результате такого умножения возникает число больше 9, оно уменьшается на значение 9;

- Все полученные в результате преобразования 16 цифр складываются.
  Если сумма кратна 10, то исходные данные верны.

Ваша задача  - написать функцию luhn_algorithm, которая проверяет,
является ли переданный номер карты валидным в соответствии с алгоритмом Луна.
Функция luhn_algorithm должна вернуть True, если номер карты валидный, в противном случае - False.
"""


def luhn_algorithm(card_number) -> bool:
    # Убираем пробелы и дефисы, если они есть
    digits = [int(d) for d in str(card_number) if d.isdigit()]
    total = 0
    # Идём справа налево: индекс i от 0 до 15, где 0—самая правая цифра
    for i, digit in enumerate(reversed(digits)):
        # Нечётные места справа налево (i = 0, 2, 4, ...) — без изменений
        # Чётные места справа налево (i = 1, 3, 5, ...) — умножаем на 2
        if i % 2 == 1:
            digit *= 2
            if digit > 9:
                digit -= 9
        total += digit

    return total % 10 == 0


print(luhn_algorithm(3942682966937054))