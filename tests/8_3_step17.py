""" 
Команда grep
В операционной системе Linux существует очень полезная утилита под названием grep. 
Ее название расшифровывается  как «global regular expression print». 
Команда grep считается среди пользователей одной из наиболее популярных и востребованных. 
Она может помочь решить множество разноплановых задач: 
найти файл с конкретной строкой в файловой системе или, наоборот, строку в файле, 
где содержатся определенные символы.

При этом с ее помощью можно не просто находить куски текста, 
но и с высокой эффективностью фильтровать вывод другой команды.

Мы напишем упрощенную версию данной утилиты, 
которая позволяет искать шаблон строки pattern в переданном тексте. 
Для этого нужно написать корутину grep, 
которая сперва принимает на вход шаблон pattern 
и затем постоянно ожидает получить на вход строки текста. 
Задача корутины grep выводить только те переданные строки, 
в которых будет найден шаблон pattern без учета регистра.
"""


def grep(pattern):
    # Приводим шаблон к нижнему регистру для регистронезависимого поиска
    pattern_lower = pattern.lower()

    while True:
        line = yield  # Корутина ожидает получения строки через .send(line)
        if line is None:
            break

        # Проверяем наличие шаблона в строке (без учёта регистра)
        if pattern_lower in line.lower():
            print(line)


search = grep('кору')
next(search)
search.send("Короед любит есть дерево")
search.send("Корутины полезно знать")
search.send("Ненавижу бесконченые циклы")
search.send("Ору с это задачи")
search.send("Какая же эта тема про корутины непонятная")
search.close()
