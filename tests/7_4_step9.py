""" 
Превращаем вложенный словарь в плоский
Перед вами имеется вложенный словарь, уровень вложенности произвольный и заранее неизвестен. 
Ключами словаря на любом уровне могут быть только строки, значениями - только числа. 

Учитывая указанные выше условия, ваша задача состоит в том, 
чтобы преобразовать этот вложенный словарь в плоский (состоящий только из одного уровня), 
где ключи формируются конкатенацией вложенных ключей, соединенных знаком _

Для этого необходимо определить рекурсивную функцию flatten_dict. 
Она должна принимать вложенный словарь и возвращать плоский.

Ваша задача только написать определение функции flatten_dict.
"""


def flatten_dict(dct, parent_key='', sep='_'):
    result_dct = {}
    for k, v in dct.items():
        new_key = f"{parent_key}{sep}{k}" if parent_key else k
        if isinstance(v, dict):
            result_dct.update(flatten_dict(v, new_key, sep=sep))
        else:
            result_dct[new_key] = v
    return result_dct

""" 
Объяснение работы функции по шагам.
Параметры функции

nested_dict — входной вложенный словарь, который нужно «сплющить».
parent_key — накопленный ключ из предыдущих уровней вложенности (по умолчанию пустая строка). 
Он нужен, чтобы собирать полную цепочку ключей.
sep — разделитель между частями ключа (по умолчанию _).
Подготовка пустого словаря items.
В него будут собираться пары «ключ — значение» для плоского словаря.

Перебор пар ключ‑значение
Цикл for k, v in nested_dict.items() проходит по всем элементам текущего уровня словаря.

Формирование нового ключа.

new_key = f"{parent_key}{sep}{k}" if parent_key else k
Если есть родительский ключ (parent_key не пустой), 
то новый ключ — это родительский ключ + разделитель + текущий ключ.
Если родительского ключа нет (мы на самом верхнем уровне), 
то new_key равен просто текущему ключу k.

Рекурсивный случай: значение — словарь

if isinstance(v, dict):
    items.update(flatten_dict(v, new_key, sep=sep))
Если значение v — это словарь, функция вызывает сама себя для этого вложенного словаря, 
передавая туда уже собранный new_key. 
Результат рекурсивного вызова (плоский словарь для этой ветки) добавляется в items через update.

Базовый случай: значение — не словарь

else:
    items[new_key] = v
Если значение не словарь (в вашей задаче это число), 
мы просто записываем пару new_key: v в итоговый словарь. 
Это останавливает рекурсию для этой ветки.

Возврат результата
После прохода по всем элементам функция возвращает items — плоский словарь, 
где ключи — это конкатенации вложенных ключей через _, а значения — числа.
"""

print(flatten_dict({'Q': {'w': {'E': {'r': {'T': {'y': 123}}}}}}))
print(flatten_dict({'Germany_berlin': 7,
                    'Europe_italy_Rome': 3,
                    'USA_washington': 1,
                    'USA_New York': 4}))
