"""
Лучшая оценка
За все время обучения студенты сдают массу экзаменов и получают за них оценки.
Университет решил собрать информацию о лучшей оценке у каждого студента.
Ваша задача написать программу, которая проанализирует результаты всех экзаменов
и найдет для каждого студента лучший балл

Напишите функцию get_info_marks, которая имеет следующие параметры:

— students содержит имена студентов в виде списка
(можете переименовать параметр по своему усмотрению). Это обязательный параметр;

— marks - произвольное количество списков, в которых содержатся оценки
(можете переименовать параметр по своему усмотрению).

Функция get_info_marks должна найти лучшую оценку для каждого студента
и составить из этих данных словарь, где ключ - имя студента, значение - лучшая оценка.

Что касается оценок, это представляет собой несколько списков из целых чисел.
Каждый список содержит оценки для студентов за один конкретный экзамен.
По месту оценки в списке определяется, к какому студенту она относится.
"""


def get_info_marks(stds, *marks):
    """
    Возвращает словарь: ключ — имя студента, значение — его лучшая оценка

    :param stds: список имён студентов (обязательный параметр)
    :param marks: произвольное количество списков с оценками (по одному списку на экзамен)
    :return: словарь {имя_студента: лучшая_оценка}
    """
    # zip объединяет оценки по позициям: для каждого студента получаем кортеж его оценок
    students_marks = zip(*marks)

    # Для каждого студента находим максимальную оценку и формируем пару (имя, макс_оценка)
    result_pairs = map(lambda pair: (pair[0], max(pair[1])), zip(stds, students_marks))

    return dict(result_pairs)


math = [90, 76, 94]
history = [78, 79, 90]
students = ["Marie", "Michael", "Marge"]
print(get_info_marks(students, math, history))
